# -*- coding: utf-8 -*-
"""
Конфигурация скрипта.
Централизованные настройки для всех бэкендов.
"""

# =============================================================================
# НАСТРОЙКИ КЛАВИШ
# =============================================================================

# Клавиша для включения/выключения перехвата (пауза)
# Доступные значения: 'f12', 'scroll_lock', 'pause', 'none' (отключено)
PAUSE_KEY = 'f12'

# Клавиши для прокрутки вверх/вниз
SCROLL_UP_KEY = 'page_up'       # page_up, up, none
SCROLL_DOWN_KEY = 'page_down'   # page_down, down, none

# Модификаторы для горизонтальной прокрутки (Shift + клавиша)
HORIZONTAL_SCROLL_ENABLED = True  # Включить горизонтальную прокрутку

# =============================================================================
# НАСТРОЙКИ ПРОКРУТКИ
# =============================================================================

# Тип прокрутки: 'page' (постранично) или 'line' (по строкам)
SCROLL_TYPE = 'page'

# Количество строк за одно нажатие (работает только если SCROLL_TYPE = 'line')
# Рекомендуемые значения: 3-10 строк
SCROLL_LINES = 5

# Количество колонок за одно нажатие (для горизонтальной прокрутки)
SCROLL_COLUMNS = 10

# =============================================================================
# НАСТРОЙКИ ОКОН (WHITELIST)
# =============================================================================

# Классы окон Windows, которые считаются терминалами
WINDOWS_TERMINAL_CLASSES = [
    # Стандартные консоли Windows
    "ConsoleWindowClass",        # cmd.exe, PowerShell 5-, Conda Prompt
    "Console-Host-UI",           # PowerShell 7+
    "CASCADIA_HOST",             # Windows Terminal (новый)
    "WindowsTerminal",           # Альтернативное имя Windows Terminal

    # Сторонние терминалы
    "git-bash",                  # Git Bash
    "mintty",                    # MinTTY (используется в Git Bash, Cygwin)
    "ConEmu",                    # ConEmu
    "Cmder",                     # Cmder
    "KiTTY",                     # KiTTY (форк PuTTY, SSH-клиент)
    "PuTTY",                     # PuTTY

    # IDE и редакторы со встроенными терминалами
    "JETBRAINS",                 # IntelliJ IDEA, PyCharm, etc.
    "Code",                      # VS Code (встроенный терминал)
]

# =============================================================================
# НАСТРОЙКИ ПРОКРУТКИ КОЛЕСОМ МЫШИ (эмуляторы терминалов)
# =============================================================================

# Классы окон, которые НЕ реагируют на WM_VSCROLL (сами рендерят текст).
# Для них PgUp/PgDn конвертируются в синтетическое колесо мыши
# (WM_MOUSEWHEEL): tmux с включённым `mouse on` ловит такие события,
# сам заходит в копи-режим и листает свою внутреннюю историю.
WHEEL_WINDOW_CLASSES = [
    "KiTTY",
    "PuTTY",
]

# Насечек колеса за одно нажатие клавиши.
# Одна насечка = WHEEL_DELTA (120) ~ 5 строк истории tmux.
WHEEL_NOTCHES_PAGE = 4   # при SCROLL_TYPE = 'page' (~полэкрана tmux)
WHEEL_NOTCHES_LINE = 1   # при SCROLL_TYPE = 'line'

# =============================================================================
# НАСТРОЙКИ ЛОГИРОВАНИЯ
# =============================================================================

# Уровень логирования: DEBUG, INFO, WARNING, ERROR, CRITICAL
LOG_LEVEL = "INFO"

# Файл лога отключён (логи выводятся в консоль)
LOG_FILE = None

# Максимальный размер файла лога в байтах (не используется)
LOG_MAX_BYTES = 1048576

# Количество резервных файлов лога (не используется)
LOG_BACKUP_COUNT = 3

# =============================================================================
# НАСТРОЙКИ ПОВЕДЕНИЯ
# =============================================================================

# Включить визуальное уведомление при паузе (всплывающее сообщение)
SHOW_PAUSE_NOTIFICATION = True

# =============================================================================
# СЛУЖЕБНЫЕ НАСТРОЙКИ
# =============================================================================

